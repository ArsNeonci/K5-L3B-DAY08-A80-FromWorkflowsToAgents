"""Export the hand-labelled adversarial claims (tests/adversarial_cases.py) for lab8.benchmark.

python scripts/export_adversarial_cases.py
python -m lab8.benchmark --shapes workflow,single,orchestrator,swarm \
    --cases tests/fixtures/adversarial_claims.jsonl --world tests/fixtures/adversarial_world.json \
    --seeds 11,22,33,44,55 --out reports/adversarial_benchmark.json

Labels are hand-written from docs/business_rules.md, not generated by lab8.compensation.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tests.adversarial_cases import CASES_ADV, WORLD_ADV  # noqa: E402


def main() -> int:
    out = ROOT / "tests" / "fixtures"
    out.mkdir(parents=True, exist_ok=True)
    (out / "adversarial_world.json").write_text(json.dumps(WORLD_ADV, ensure_ascii=False, indent=2), encoding="utf-8")
    with (out / "adversarial_claims.jsonl").open("w", encoding="utf-8") as handle:
        for case in CASES_ADV:
            handle.write(json.dumps(case, ensure_ascii=False) + "\n")
    print(f"wrote {len(CASES_ADV)} claims to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
